"""GAS Rev C circuit board.

Plugin order: tank returns + Ext Mix -> HPF -> Gain (+/-18 dB, pull = Dirt TS808) -> Comp (FET) / Off / Limit (VCA) -> LPF
-> WET out (to io-board Wet/Dry) and the feedback path: Feedback amount -> FB phase -> MEGAVERB L/R swap -> FB_RET (to tank board).
Bus scale 0 dBFS = 6.93 Vpk (HPF gain 1.59), board I/O 0 dBFS = 4.36 Vpk. Pedal stages 0.1 Vpk per full scale.
"""
from core import *
from common import *


def build():
    b = Board("circuit-board", "GAS Rev C - Circuit board (Ext Mix, HPF, Gain/Dirt, Comp/Limit, LPF, Feedback, MEGAVERB)",
              ["Rev C: replaces Rev B circuit-board and the Rev A crossfade/feedback/wet board",
               "Gain pull = TS808 (relay K1), FB Dyn toggle = FET comp (K2) / off / VCA limit (K3)",
               "Feedback pot + FB phase (K4) + MEGAVERB swap (K5) now live here; FB_RET goes to the tank board",
               "Generated by revc/gen/boards/circuit_board.py (netlist-by-label). See rev-c-hardware-definition.md"])
    b.outline = (120.0, 175.0)
    b.power_nets = {"AGND", "+15VA", "-15VA", "+5VAUX", "+9VC"}

    B = "Connectors"
    b.XH("P1", "TANK-RET (from tank board)", ["PRI_RET_L", "AGND", "PRI_RET_R", "SEC_RET_L", "AGND", "SEC_RET_R"], B)
    b.XH("P2", "WET-OUT (to io-board)", ["WET_L", "AGND", "WET_R"], B)
    b.XH("P3", "FB-RET (to tank board)", ["FB_RET_L", "AGND", "FB_RET_R"], B)
    power_in(b, "P4", B)
    b.XH("P5", "CTL-A: HPF quad 50k lin (PTD904-2015K-B503) on its filter-pot riser P1",
         ["HPF_OUT_L", "HPF_L1_W", "AGND", "HPF_L2_W", "HPF_OUT_R", "HPF_R1_W", "AGND", "HPF_R2_W"], B,
         Description="each gang: CCW end = HI, wiper and CW end tied = W, both done on the riser. CW lowers the corner")
    b.XH("P9", "CTL-E: Gain dual 10k lin (control deck P4)",
         ["GAIN_L_HI", "GAIN_L_W", "GAIN_L_LO", "GAIN_R_HI", "GAIN_R_W", "GAIN_R_LO"], B)
    b.XH("P6", "CTL-B: LPF quad 50k lin (PTD904-2015K-B503) on its filter-pot riser P1",
         ["LPF_N1_L", "LPF_L1_W", "LPF_P_L", "LPF_L2_W", "LPF_N1_R", "LPF_R1_W", "LPF_P_R", "LPF_R2_W"], B,
         Description="each gang: CCW end = HI, wiper and CW end tied = W, both done on the riser. CW lowers the corner")
    b.XH("P8", "CTL-D: switch lines (from control deck)",
         ["CTL_DIRT", "CTL_COMP", "CTL_LIMIT", "CTL_MEGA", "CTL_FB_INV", "+5VAUX", "AGND"], B,
         Description="1 Gain pull switch, 2/3 FB Dyn toggle up/down, 4 Source toggle MEGAVERB throw, 5 FB Phase toggle, 6 +5VAUX, 7 AGND")
    b.XH("P7", "CTL-C: Ext Mix dual 10k lin, Feedback dual 10k lin",
         ["SEC_BUF_L", "EXM_L_W", "AGND", "SEC_BUF_R", "EXM_R_W", "AGND",
          "WET_RAW_L", "FBP_L_W", "AGND", "WET_RAW_R", "FBP_R_W", "AGND"], B,
         Description="each pot: HI / wiper / LO(AGND)")
    for i, (x, y) in enumerate(((4, 4), (116, 4), (4, 171), (116, 171))):
        b.HOLE(f"H{i + 1}", x, y)

    B = "Power, +9VC, VBIAS"
    bulk(b, "C110", "+15VA", B); bulk(b, "C111", "-15VA", B)
    tl_vbias(b, "10", B, "U102")
    b.OPA2("U102", {1: ("VB_RAW", "VBIAS", "VBIAS")}, B, value="TL072HIDR", vp="+9VC", vn="AGND")
    dec(b, "C105", "+9VC", B)

    for ch, n in (("L", 2), ("R", 3)):
        o = "R" if ch == "L" else "L"
        B = f"Main path {ch}: Ext Mix sum, HPF, Gain, LPF"
        # secondary return buffer for the Ext Mix pot HI end
        b.R(f"R{n}20", "100k", f"PRI_RET_{ch}", f"MIX_N_{ch}", B)
        b.R(f"R{n}21", "100k", f"EXM_{ch}_W", f"MIX_N_{ch}", B, Description="Ext Mix: additive, 0..100 % of the 2nd tank (100k keeps the 10k pot law within 2.5 %)")
        b.R(f"R{n}22", "100k", f"MIX_N_{ch}", f"TANK_MIX_{ch}", B)
        b.C(f"C{n}20", "22pF", f"MIX_N_{ch}", f"TANK_MIX_{ch}", B, MPN="CL10C220JB8NNNC", Manufacturer="Samsung")
        b.R(f"R{n}23", "100k", f"PRI_RET_{ch}", "AGND", B, Description="input bias if the harness is unplugged")
        b.R(f"R{n}24", "100k", f"SEC_RET_{ch}", "AGND", B)
        # HPF Sallen-Key, K = 1.59, Q 0.71, R = 499R + 50k gang, C = 2 x 68 nF (same 23 Hz .. 2.3 kHz sweep and law as 1k + 100k)
        # 2026-09-30: HPF moved AHEAD of the Gain stage to match the plugin (RevCStages.h: pre-HPF -> Gain
        # -> [Tube Screamer] -> [Comp | Off | Limit] -> post-LPF). Both stages are linear, so response and
        # overall level are unchanged, but the springs put a lot of subsonic energy on TANK_MIX and this
        # strips it before the Gain stage can amplify it by up to 18 dB into the TS808 clipper.
        b.C(f"C{n}02", "68nF film", f"TANK_MIX_{ch}", f"HPF_N1_{ch}", B, fp=FP_C1210, MPN="ECH-U1H683JX5", Manufacturer="Panasonic")
        b.C(f"C{n}12", "68nF film", f"TANK_MIX_{ch}", f"HPF_N1_{ch}", B, fp=FP_C1210, MPN="ECH-U1H683JX5", Manufacturer="Panasonic")
        b.C(f"C{n}03", "68nF film", f"HPF_N1_{ch}", f"HPF_P_{ch}", B, fp=FP_C1210, MPN="ECH-U1H683JX5", Manufacturer="Panasonic")
        b.C(f"C{n}13", "68nF film", f"HPF_N1_{ch}", f"HPF_P_{ch}", B, fp=FP_C1210, MPN="ECH-U1H683JX5", Manufacturer="Panasonic")
        b.R(f"R{n}04", "499R", f"HPF_N1_{ch}", f"HPF_{ch}1_W", B)
        b.R(f"R{n}05", "499R", f"HPF_P_{ch}", f"HPF_{ch}2_W", B)
        b.R(f"R{n}06", "5.9k", f"HPF_OUT_{ch}", f"HPF_FB_{ch}", B)
        b.R(f"R{n}07", "10k", f"HPF_FB_{ch}", "AGND", B)
        b.R(f"R{n}08", "1M", f"HPF_P_{ch}", "AGND", B)
        # Gain pot stage, now fed from the HPF output
        gain = pot_stage(b, f"{n}0", f"HPF_OUT_{ch}", f"GAIN_{ch}_HI", f"GAIN_{ch}_W", f"GAIN_{ch}_LO", f"GAIN_OUT_{ch}", None, None, B)
        # pad to pedal level, off the Gain stage output
        b.R(f"R{n}15", "47k", f"GAIN_OUT_{ch}", f"PAD_{ch}", B)
        b.R(f"R{n}16", "680R", f"PAD_{ch}", "AGND", B, Description="0.01426: 6.93 Vpk bus -> 0.1 Vpk")
        # LPF Sallen-Key unity, Q 0.74
        b.R(f"R{n}11", "100k", f"BUS_{ch}", "AGND", B)
        b.R(f"R{n}09", "499R", f"BUS_{ch}", f"LPF_{ch}1_W", B, Description="499R + 50k gang, caps doubled: same sweep as 1k + 100k")
        b.R(f"R{n}10", "499R", f"LPF_N1_{ch}", f"LPF_{ch}2_W", B)
        b.C(f"C{n}04", "15nF film", f"LPF_N1_{ch}", f"LPF_OUT_{ch}", B, fp=FP_C1206, MPN="ECH-U1H153JX5", Manufacturer="Panasonic")
        b.C(f"C{n}14", "15nF film", f"LPF_N1_{ch}", f"LPF_OUT_{ch}", B, fp=FP_C1206, MPN="ECH-U1H153JX5", Manufacturer="Panasonic")
        b.C(f"C{n}05", "6.8nF film", f"LPF_P_{ch}", "AGND", B, fp=FP_C0805, MPN="ECH-U1H682JX5", Manufacturer="Panasonic")
        b.C(f"C{n}15", "6.8nF film", f"LPF_P_{ch}", "AGND", B, fp=FP_C0805, MPN="ECH-U1H682JX5", Manufacturer="Panasonic")
        # Units follow the signal order (1 Ext Mix sum, 2 HPF, 3 Gain, 4 LPF) so the traces run
        # straight down the quad instead of doubling back. Swapped with the stage order, 2026-09-30.
        b.OPA4(f"U{n}01", {1: ("AGND", f"MIX_N_{ch}", f"TANK_MIX_{ch}"),
                           2: (f"HPF_P_{ch}", f"HPF_FB_{ch}", f"HPF_OUT_{ch}"), 3: gain,
                           4: (f"LPF_P_{ch}", f"LPF_OUT_{ch}", f"LPF_OUT_{ch}")}, B)
        dec(b, f"C{n}07", "+15VA", B); dec(b, f"C{n}08", "-15VA", B)

        B = f"Output, feedback, make-ups {ch}"
        b.R(f"R{n}12", "15.8k", f"LPF_OUT_{ch}", f"OB_N_{ch}", B, Description="inverting x-1/1.59: back to 4.36 Vpk per full scale, and restores loop polarity (even number of inversions)")
        b.R(f"R{n}13", "10k", f"OB_N_{ch}", f"WET_RAW_{ch}", B)
        b.C(f"C{n}11", "22pF", f"OB_N_{ch}", f"WET_RAW_{ch}", B, MPN="CL10C220JB8NNNC", Manufacturer="Samsung")
        b.R(f"R{n}14", "100R", f"WET_RAW_{ch}", f"WET_{ch}", B)
        b.R(f"R{n}30", "100R", f"SEC_RET_{ch}", f"SEC_BUF_{ch}", B, Description="Ext Mix pot HI end, fed from the tank board recovery amp")
        b.R(f"R{n}31", "20k", f"FB_BUF_{ch}", f"FBI_N_{ch}", B)
        b.R(f"R{n}32", "20k", f"FBI_N_{ch}", f"FB_INV_{ch}", B)
        b.R(f"R{n}33", "100R", f"FB_RAW_{ch}", f"FB_RET_{ch}", B)
        b.R(f"R{n}34", "1M", f"FBP_{ch}_W", "AGND", B)
        b.R(f"R{n}35", "59k", f"TS_OUT_{ch}", f"TS_FB2_{ch}", B, Description="TS make-up x6.9 (+1.4 dB clean, as the plugin)")
        b.R(f"R{n}36", "10k", f"TS_FB2_{ch}", "AGND", B)
        b.OPA4(f"U{n}02", {1: ("AGND", f"OB_N_{ch}", f"WET_RAW_{ch}"), 2: (f"TS_DIV_{ch}", f"TS_FB2_{ch}", f"TS_OUT_{ch}"),
                           3: (f"FBP_{ch}_W", f"FB_BUF_{ch}", f"FB_BUF_{ch}"), 4: ("AGND", f"FBI_N_{ch}", f"FB_INV_{ch}")}, B)
        dec(b, f"C{n}09", "+15VA", B); dec(b, f"C{n}10", "-15VA", B)

        B = f"Tube Screamer {ch}: Rf 51k / Rg 4.7k, 1N4148W pair, +9VC"
        m = 8 if ch == "L" else 9
        film1u(b, f"C{m}01", f"PAD_{ch}", f"TS_IN_{ch}", B)
        b.R(f"R{m}01", "100k", f"TS_IN_{ch}", "VBIAS", B)
        b.R(f"R{m}02", "4.7k", f"TS_FB_{ch}", "VBIAS", B)
        b.R(f"R{m}03", "51k", f"TS_CLIP_{ch}", f"TS_FB_{ch}", B)
        b.D(f"D{m}01", "1N4148W", f"TS_FB_{ch}", f"TS_CLIP_{ch}", B, MPN="1N4148W-7-F", Manufacturer="Diodes Incorporated")
        b.D(f"D{m}02", "1N4148W", f"TS_CLIP_{ch}", f"TS_FB_{ch}", B, MPN="1N4148W-7-F", Manufacturer="Diodes Incorporated")
        b.C(f"C{m}03", "51pF", f"TS_CLIP_{ch}", f"TS_FB_{ch}", B, MPN="CL10C510JB8NNNC", Manufacturer="Samsung")
        film1u(b, f"C{m}04", f"TS_CLIP_{ch}", f"TS_DIV_{ch}", B)
        b.R(f"R{m}04", "100k", f"TS_DIV_{ch}", "AGND", B)

    b.OPA2("U402", {1: ("TS_IN_L", "TS_FB_L", "TS_CLIP_L"), 2: ("TS_IN_R", "TS_FB_R", "TS_CLIP_R")},
           "Tube Screamer L: Rf 51k / Rg 4.7k, 1N4148W pair, +9VC", value="TL072HIDR", vp="+9VC", vn="AGND")
    dec(b, "C805", "+9VC", "Tube Screamer L: Rf 51k / Rg 4.7k, 1N4148W pair, +9VC")

    # ---------------------------------------------------------------- FET compressor (12xx)
    B = "Comp: MMBF5457 FET compressor (1176 territory), linked feedback sidechain"
    for ch, n in (("L", 120), ("R", 122)):
        b.R(f"R{n}1", "22k", f"DYN_IN_{ch}", f"FET_DIV_{ch}", B)
        b.R(f"R{n}2", "2.2k", f"FET_DIV_{ch}", "AGND", B)
        b.NJFET(f"Q{n}1", "MMBF5457", f"FET_DIV_{ch}", f"FET_G_{ch}", "AGND", B,
                Description="was 2N5457 TO-92 (obsolete). RV reaches Vgs -5.1 V: screen for |Vgs(off)| < 5 V")
        b.R(f"R{n}3", "1M", f"FET_G_{ch}", f"FET_CV_{ch}", B)
        b.R(f"R{n}4", "1M", f"FET_G_{ch}", f"FET_DIV_{ch}", B)
        b.R(f"R{n}5", "47k", f"FET_CV_{ch}", f"FET_BIAS_{ch}", B)
        b.R(f"R{n}6", "100k", f"FET_CV_{ch}", "FET_SC", B)
        b.TRIM(f"RV{n}1", "10k", "-15VA", f"FET_BIAS_{ch}", "AGND", B, MPN="3314J-1-103E", Manufacturer="Bourns",
               Description="threshold: gain just starts to drop at -18 dBFS")
        b.R(f"R{n}7", "100k", f"FET_OUT_{ch}", f"FET_MK_{ch}", B)
        b.R(f"R{n}8", "10k", f"FET_MK_{ch}", "AGND", B)
    b.R("R1241", "20k", "FET_OUT_L", "SC2_N", B)
    b.R("R1242", "20k", "FET_OUT_R", "SC2_N", B)
    b.R("R1243", "40.2k", "SC2_N", "SC2_SUM", B, Description="sidechain summer x4 over (L+R)/2, as the Rev C plugin")
    b.R("R1244", "10k", "SC2_SUM", "SC2_RN", B)
    b.D("D1241", "1N4148W", "SC2_RN", "SC2_OP", B, MPN="1N4148W-7-F", Manufacturer="Diodes Incorporated")
    b.D("D1242", "1N4148W", "SC2_OP", "SC2_X", B, MPN="1N4148W-7-F", Manufacturer="Diodes Incorporated")
    b.R("R1245", "10k", "SC2_X", "SC2_RN", B)
    b.D("D1243", "1N5819HW", "SC2_X", "SC2_PK", B, lib="Device:D_Schottky", MPN="1N5819HW-7-F", Manufacturer="Diodes Incorporated")
    b.R("R1246", "1.5k", "SC2_PK", "SC2_ENV", B, Description="150 us attack")
    b.C("C1241", "100nF", "SC2_ENV", "AGND", B, MPN="CL10B104KB8NNNC", Manufacturer="Samsung")
    b.R("R1247", "2.2M", "SC2_ENV", "AGND", B, Description="220 ms release")
    b.OPA4("U1201", {1: ("FET_DIV_L", "FET_MK_L", "FET_OUT_L"), 2: ("FET_DIV_R", "FET_MK_R", "FET_OUT_R"),
                     3: ("AGND", "SC2_N", "SC2_SUM"), 4: ("AGND", "SC2_RN", "SC2_OP")}, B)
    dec(b, "C1201", "+15VA", B); dec(b, "C1202", "-15VA", B)

    # ---------------------------------------------------------------- VCA limiter (13xx)
    B = "Limit: Coolaudio V2181 VCA x2 (THAT 2181 pin-compatible), discrete log-average detector (feedback), 10:1"
    for ch, n, U in (("L", 130, "U1303"), ("R", 132, "U1304")):
        b.R(f"R{n}1", "20k", f"DYN_IN_{ch}", f"VCA_IN_N_{ch}", B)
        b.R(f"R{n}2", "20k", f"VCA_IN_N_{ch}", f"VCA_INV_{ch}", B)
        film1u(b, f"C{n}1", f"VCA_INV_{ch}", f"VCA_C_{ch}", B)
        b.R(f"R{n}3", "20k", f"VCA_C_{ch}", f"VCA_IN_{ch}", B)
        b.add(U, "GAS_Parts:THAT2180", "V2181", FP_SIP8,
              {1: {"1": f"VCA_IN_{ch}", "2": "AGND", "3": "VCA_EC", "4": f"VCA_SYM_{ch}", "5": f"VCA_VN_{ch}", "6": "AGND",
                   "7": "+15VA", "8": f"VCA_O_{ch}"}}, B, MPN="V2181", Manufacturer="Coolaudio",
              Description="SIP-8, pinout = THAT 2181 (1 IN, 2 EC+, 3 EC-, 4 SYM, 5 V-, 6 GND, 7 V+, 8 OUT). Alternates: THAT 2181BL08-U, Alfa AS2181")
        b.R(f"R{n}6", "5.1k", f"VCA_VN_{ch}", "-15VA", B, Description="ISET 2.4 mA")
        b.R(f"R{n}4", "20k", f"VCA_O_{ch}", f"VCA_OUT_{ch}", B)
        b.C(f"C{n}2", "22pF", f"VCA_O_{ch}", f"VCA_OUT_{ch}", B, MPN="CL10C220JB8NNNC", Manufacturer="Samsung")
        b.TRIM(f"RV{n}1", "50k", "+15VA", f"VCA_SYMW_{ch}", "-15VA", B, MPN="3314J-1-503E", Manufacturer="Bourns",
               Description="V2181 symmetry: set for minimum THD at 1 kHz, 0 dB gain")
        b.R(f"R{n}5", "150k", f"VCA_SYMW_{ch}", f"VCA_SYM_{ch}", B, Description="symmetry range +/-2.5 mV (25R internal to pin 2)")
        dec(b, f"C{n}3", "+15VA", B); dec(b, f"C{n}4", "-15VA", B)
    b.OPA4("U1301", {1: ("AGND", "VCA_IN_N_L", "VCA_INV_L"), 2: ("AGND", "VCA_O_L", "VCA_OUT_L"),
                     3: ("AGND", "VCA_IN_N_R", "VCA_INV_R"), 4: ("AGND", "VCA_O_R", "VCA_OUT_R")}, B)
    dec(b, "C1305", "+15VA", B); dec(b, "C1306", "-15VA", B)
    B = "Limit detector + threshold"
    film1u(b, "C1341", "VCA_OUT_L", "DET_C_L", B)
    b.R("R1341", "20k", "DET_C_L", "DET_SUM_N", B)
    film1u(b, "C1342", "VCA_OUT_R", "DET_C_R", B)
    b.R("R1342", "20k", "DET_C_R", "DET_SUM_N", B)
    b.R("R1343", "10k", "DET_SUM_N", "DET_SUM", B)
    b.R("R1344", "10k", "DET_SUM", "HW_N", B)
    b.D("D1342", "1N4148W", "HW_N", "HW_OP", B, MPN="1N4148W-7-F", Manufacturer="Diodes Incorporated")
    b.D("D1343", "1N4148W", "HW_OP", "HW_X", B, MPN="1N4148W-7-F", Manufacturer="Diodes Incorporated")
    b.R("R1345", "10k", "HW_X", "HW_N", B)
    b.R("R1347", "20k", "DET_SUM", "FW_N", B)
    b.R("R1348", "10k", "HW_X", "FW_N", B)
    b.R("R1349", "20k", "FW_N", "FW_OUT", B)
    b.R("R1346", "10k", "FW_OUT", "DET_AVG", B)
    film1u(b, "C1344", "DET_AVG", "AGND", B)
    b.R("R1350", "100k", "DET_AVG", "LOG_N", B)
    b.PNP3906("Q1341", "AGND", "DET_OUT", "LOG_N", B, Description="transdiode log converter, about 3 mV/dB")
    b.C("C1343", "100pF", "LOG_N", "DET_OUT", B, MPN="CL10C101JB8NNNC", Manufacturer="Samsung")
    b.OPA4("U1305", {1: ("AGND", "DET_SUM_N", "DET_SUM"), 2: ("AGND", "HW_N", "HW_OP"),
                     3: ("AGND", "FW_N", "FW_OUT"), 4: ("AGND", "LOG_N", "DET_OUT")}, B)
    dec(b, "C1345", "+15VA", B); dec(b, "C1346", "-15VA", B)
    b.R("R1351", "10k", "DET_OUT", "TH_P", B)
    b.R("R1352", "182k", "TH_P", "AGND", B)
    b.R("R1353", "100k", "TH_REF", "TH_N", B)
    b.R("R1354", "1.82M", "TH_N", "TH_OUT", B)
    b.R("R1355", "100k", "+15VA", "TH_TOP", B)
    b.TRIM("RV1342", "10k", "TH_TOP", "TH_REF", "TH_BOT", B, MPN="3314J-1-103E", Manufacturer="Bourns",
           Description="threshold: VCA_EC just starts rising at -18 dBFS")
    b.R("R1356", "100k", "TH_BOT", "-15VA", B)
    b.D("D1341", "1N4148W", "CL_OP", "VCA_EC_RAW", B, MPN="1N4148W-7-F", Manufacturer="Diodes Incorporated")
    b.R("R1357", "10k", "VCA_EC_RAW", "AGND", B)
    b.OPA4("U1302", {1: ("TH_P", "TH_N", "TH_OUT"), 2: ("TH_OUT", "VCA_EC_RAW", "CL_OP"),
                     3: ("SC2_ENV", "FET_SC", "FET_SC"), 4: ("VCA_EC_RAW", "VCA_EC", "VCA_EC")}, B)
    dec(b, "C1307", "+15VA", B); dec(b, "C1308", "-15VA", B)

    # ---------------------------------------------------------------- relays
    B = "Relays: Dirt, Comp, Limit, FB phase, MEGAVERB (Omron G6K-2F-Y 5 V)"
    b.RELAY("K1", "CTL_DIRT", "DYN_IN_L", "GAIN_OUT_L", "TS_OUT_L", "DYN_IN_R", "GAIN_OUT_R", "TS_OUT_R", B, Description="Gain pull: Dirt")
    b.RELAY("K2", "CTL_COMP", "DYN_MID_L", "DYN_IN_L", "FET_OUT_L", "DYN_MID_R", "DYN_IN_R", "FET_OUT_R", B, Description="FB Dyn up: Comp")
    b.RELAY("K3", "CTL_LIMIT", "BUS_L", "DYN_MID_L", "VCA_OUT_L", "BUS_R", "DYN_MID_R", "VCA_OUT_R", B, Description="FB Dyn down: Limit")
    b.RELAY("K4", "CTL_FB_INV", "FB_SEL_L", "FB_BUF_L", "FB_INV_L", "FB_SEL_R", "FB_BUF_R", "FB_INV_R", B, Description="FB Phase")
    b.RELAY("K5", "CTL_MEGA", "FB_RAW_L", "FB_SEL_L", "FB_SEL_R", "FB_RAW_R", "FB_SEL_R", "FB_SEL_L", B,
            Description="Source toggle MEGAVERB: L path feedback -> R path input and R -> L")
